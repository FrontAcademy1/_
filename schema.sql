-- Profiles: a user may read only their own profile.
-- There is intentionally NO public INSERT policy, preventing self-promotion to admin.
create policy "profiles_select_own"
on public.profiles for select to authenticated
using (id = auth.uid());

-- Public chapters/categories are readable. Writes are admin-only.
create policy "chapters_public_select"
on public.chapters for select to anon, authenticated
using (true);

create policy "chapters_admin_insert"
on public.chapters for insert to authenticated
with check (public.is_admin());

create policy "chapters_admin_update"
on public.chapters for update to authenticated
using (public.is_admin()) with check (public.is_admin());

create policy "chapters_admin_delete"
on public.chapters for delete to authenticated
using (public.is_admin());

create policy "categories_public_select"
on public.categories for select to anon, authenticated
using (true);

create policy "categories_admin_insert"
on public.categories for insert to authenticated
with check (public.is_admin());

create policy "categories_admin_update"
on public.categories for update to authenticated
using (public.is_admin()) with check (public.is_admin());

create policy "categories_admin_delete"
on public.categories for delete to authenticated
using (public.is_admin());

-- Questions: public sees only published records.
create policy "questions_public_published_select"
on public.questions for select to anon, authenticated
using (published = true);

-- Admin sees and manages all questions.
create policy "questions_admin_select"
on public.questions for select to authenticated
using (public.is_admin());

create policy "questions_admin_insert"
on public.questions for insert to authenticated
with check (public.is_admin());

create policy "questions_admin_update"
on public.questions for update to authenticated
using (public.is_admin()) with check (public.is_admin());

create policy "questions_admin_delete"
on public.questions for delete to authenticated
using (public.is_admin());

-- Public settings only when explicitly marked public.
create policy "settings_public_select"
on public.site_settings for select to anon, authenticated
using (is_public = true);

create policy "settings_admin_select"
on public.site_settings for select to authenticated
using (public.is_admin());

create policy "settings_admin_insert"
on public.site_settings for insert to authenticated
with check (public.is_admin());

create policy "settings_admin_update"
on public.site_settings for update to authenticated
using (public.is_admin()) with check (public.is_admin());

create policy "settings_admin_delete"
on public.site_settings for delete to authenticated
using (public.is_admin());

